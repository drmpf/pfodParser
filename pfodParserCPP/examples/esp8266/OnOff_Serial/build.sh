# build.sh -- builds this OnOff_Serial example for an ESP8266 with ESP8266_RTOS_SDK
# (release/v3.4) and its idf.py / CMake build, in a generated project in build/project.
#
# ESP8266_RTOS_SDK builds on Linux / macOS (on Windows run this in WSL, e.g.
#   wsl bash build.sh
# from this directory). It does not run under Git Bash.
#   bash build.sh               build
#   bash build.sh --delete-sdk  build, then delete the SDK, toolchain and python env
#                               that build.sh downloaded (the build output is kept)
# Output: build/project/build/OnOff_Serial.bin, bootloader/bootloader.bin and
# partition_table/partition-table.bin, and the flash command idf.py prints, e.g.
#   (cd build/project && idf.py -p /dev/ttyUSB0 flash)
#
# The SDK, toolchain and python packages come from (first found):
#   IDF_PATH                an ESP8266_RTOS_SDK checkout, else a shallow clone (with
#                           submodules) into build/ESP8266_RTOS_SDK
#   xtensa-lx106-elf-gcc    on the PATH, else Espressif's gcc 8.4.0-esp-2020r3 for
#                           this OS downloaded into build/xtensa-lx106-elf
#   python packages         SDK requirements.txt + cmake + ninja, pip installed into
#                           a python venv in build/venv (needs python3 with venv)
# PFOD_PARSER_CPP overrides the pfodParserCPP directory, default three directories up from here.
# About 400MB is downloaded the first time; it is kept for the next build unless
# --delete-sdk is given.
#
# The ESP8266 console / log output is on UART0, the same UART as the pfod connection
# (see main.cpp). pfodWeb ignores characters outside the {..} messages.

set -u

EX="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "${PFOD_PARSER_CPP:-$EX/../../..}" && pwd)"
OUT="$EX/build"
DELETE_SDK=0
[ "${1:-}" = "--delete-sdk" ] && DELETE_SDK=1
SDK_BRANCH=release/v3.4
TC_VERSION=gcc8_4_0-esp-2020r3
DOWNLOADED=() # what to delete for --delete-sdk

# fail -- print an error and stop
fail() {
  echo "ERROR: $*" >&2
  exit 1
}

case "$(uname -s)" in
  Linux) TC_OS=linux-amd64 ;;
  Darwin) TC_OS=macos ;;
  *) fail "ESP8266_RTOS_SDK builds on Linux / macOS, on Windows run this in WSL: wsl bash build.sh" ;;
esac
mkdir -p "$OUT"

# ---- SDK ----
if [ -z "${IDF_PATH:-}" ]; then
  export IDF_PATH="$OUT/ESP8266_RTOS_SDK"
  DOWNLOADED+=("$IDF_PATH")
  if [ ! -d "$IDF_PATH/components" ]; then
    echo "Downloading ESP8266_RTOS_SDK $SDK_BRANCH into $IDF_PATH"
    git clone -q --depth 1 --recursive --shallow-submodules -b "$SDK_BRANCH" \
      https://github.com/espressif/ESP8266_RTOS_SDK.git "$IDF_PATH" || fail "git clone of ESP8266_RTOS_SDK failed"
  fi
fi
[ -e "$IDF_PATH/tools/idf.py" ] || fail "IDF_PATH $IDF_PATH is not an ESP8266_RTOS_SDK checkout"
echo "SDK: $IDF_PATH"

# ---- toolchain ----
if ! command -v xtensa-lx106-elf-gcc >/dev/null 2>&1; then
  TCDIR="$OUT/xtensa-lx106-elf"
  DOWNLOADED+=("$TCDIR")
  if [ ! -x "$TCDIR/bin/xtensa-lx106-elf-gcc" ]; then
    echo "Downloading the xtensa-lx106-elf $TC_VERSION toolchain"
    curl -sfL "https://dl.espressif.com/dl/xtensa-lx106-elf-$TC_VERSION-$TC_OS.tar.gz" | tar -xz -C "$OUT" \
      || fail "toolchain download failed"
  fi
  export PATH="$TCDIR/bin:$PATH"
fi
echo "Toolchain: $(xtensa-lx106-elf-gcc --version | head -1)"

# ---- python env with the SDK's requirements, cmake and ninja ----
VENV="$OUT/venv"
DOWNLOADED+=("$VENV")
# .pfod_ok is written only after the pip install succeeds, so a failed or partial
# env (python3 -m venv leaves bin/python behind when it fails) is rebuilt next time
if [ ! -e "$VENV/.pfod_ok" ]; then
  echo "Creating the python env $VENV"
  rm -rf "$VENV"
  python3 -m venv "$VENV" || fail "python3 -m venv failed (on Debian/Ubuntu/WSL: sudo apt install python3-venv)"
  "$VENV/bin/python" -m pip install -q -r "$IDF_PATH/requirements.txt" cmake ninja || fail "pip install failed"
  touch "$VENV/.pfod_ok"
fi
export PATH="$VENV/bin:$PATH"

# ---- generated idf.py project: this example + pfodParserCPP src/ as the main component ----
PROJ="$OUT/project"
mkdir -p "$PROJ/main"
cat > "$PROJ/CMakeLists.txt" <<EOF
# generated by build.sh
cmake_minimum_required(VERSION 3.5)
include(\$ENV{IDF_PATH}/tools/cmake/project.cmake)
project(OnOff_Serial)
EOF
{
  echo "# generated by build.sh -- this example's files and pfodParserCPP's src/ and src/dwgs/"
  echo "idf_component_register(SRCS"
  for f in "$EX"/*.cpp "$ROOT"/src/*.cpp "$ROOT"/src/*.c "$ROOT"/src/dwgs/*.cpp; do echo "    \"$f\""; done
  echo "  INCLUDE_DIRS \"$EX\" \"$ROOT/src\")"
  echo "target_compile_options(\${COMPONENT_LIB} PRIVATE -Wall -Wextra)"
} > "$PROJ/main/CMakeLists.txt"

cd "$PROJ" || fail "cannot cd to $PROJ"
python "$IDF_PATH/tools/idf.py" build || fail "idf.py build failed"
xtensa-lx106-elf-size "$PROJ/build/OnOff_Serial.elf"

if [ $DELETE_SDK = 1 ]; then
  for d in "${DOWNLOADED[@]}"; do
    rm -rf "$d"
    echo "Deleted $d"
  done
fi
