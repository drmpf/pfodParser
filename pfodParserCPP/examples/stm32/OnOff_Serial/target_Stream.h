#ifndef target_Stream_h
#define target_Stream_h
/*
 * pfodStream implementation for STM32 (STM32Cube HAL), NOT Arduino,
 * following the pattern of Arduino's HardwareSerial.
 * Wraps a HAL UART_HandleTypeDef.
 *
 * Use it for pfodParser::connect(pfodStream*), and for debug output via
 * setDebugPtr(pfodStream*). Since a pfodStream is a pfodPrint, it can also be
 * used wherever a pfodPrint* is wanted.
 *
 * Requires the STM32Cube HAL UART driver already configured for your MCU
 * family -- clocks, GPIO alternate-function pin muxing, the UART's NVIC
 * IRQ enabled and HAL_UART_Init() called -- exactly as CubeMX/STM32CubeIDE
 * normally generates. This class only handles the byte stream part on top of
 * an already initialised UART_HandleTypeDef; it does not call HAL_UART_Init().
 *
 * The HAL header to include is chosen by PFOD_STM32_HAL_INCLUDE,
 * default "stm32f4xx_hal.h". Override it for your family, e.g. add
 * -DPFOD_STM32_HAL_INCLUDE=\"stm32l4xx_hal.h\" to your build.
 *
 * Receive is interrupt driven, one byte at a time with HAL_UART_Receive_IT(),
 * into a pfodRingBuffer, so available(), read() and peek() just use the ring buffer.
 * This class supports one UART (one instance), see target_Stream.cpp.
 *
 * write() blocks (HAL_UART_Transmit with HAL_MAX_DELAY) until the byte has been
 * sent, so flush() has nothing to wait for.
 *
 * Usage (in main.cpp):
 *   UART_HandleTypeDef huart2;      // set up by CubeMX / HAL_UART_Init() as usual
 *   uint8_t rxBuf[128];
 *   target_Stream serialStream;     // global, the constructor does not touch the hardware
 *   ...
 *   // in setup(), after the HAL / UART initialisation
 *   serialStream.begin(&huart2, rxBuf, sizeof(rxBuf)); // starts the interrupt driven receive
 *   parser.connect(&serialStream);
 *   setDebugPtr(&serialStream);     // optional, debug output on the same port
 *
 *   // stm32xxxx_it.c already has (generated by CubeMX):
 *   //   void USART2_IRQHandler(void) { HAL_UART_IRQHandler(&huart2); }
 *   // HAL_UART_IRQHandler() calls HAL_UART_RxCpltCallback() in target_Stream.cpp
 *   // once a requested byte has arrived -- no other wiring needed.
 *
 * Debug output can go out on the same port as the pfod messages. pfodWeb ignores
 * characters outside the {..} messages and logs them to the Raw Message Viewer.
 *
 * Compiled and linked against the STM32CubeF4 HAL for the STM32F401RE (build.sh), not tested on hardware -- check against your HAL version.
 */

#include "pfodStream.h"
#include "pfodRingBuffer.h"

#ifndef PFOD_STM32_HAL_INCLUDE
#define PFOD_STM32_HAL_INCLUDE "stm32f4xx_hal.h"
#endif
#include PFOD_STM32_HAL_INCLUDE

class target_Stream : public pfodStream {
  public:
    /**
     * Constructor, only initialises member variables.
     * Does NOT access the hardware, since global objects are constructed
     * before main() runs, i.e. before the board's clocks/pins are set up.
     * Call begin() from setup() to start the port.
     */
    target_Stream();

    /**
     * Start using an already HAL_UART_Init()'d UART.
     * Initialises the rx ring buffer and starts the interrupt driven receive.
     * Call once from setup() before using it, e.g. before parser.connect().
     * @param huart the HAL UART handle, already initialised by HAL_UART_Init()
     * @param rxBuf caller supplied storage for the rx ring buffer,
     *              must stay valid for the life of this stream
     * @param rxBufSize the size of rxBuf
     */
    void begin(UART_HandleTypeDef *huart, uint8_t *rxBuf, size_t rxBufSize);

    // pfodPrint methods
    using pfodStream::write; // keep inherited write(const char*) visible

    /**
     * Write one byte to the UART, blocking until it has been sent.
     * @param c the byte to send
     * @return 1 if the byte was sent, 0 if not (including if begin() has not been called).
     */
    size_t write(uint8_t c) override;

    /**
     * Write a block of bytes with one HAL_UART_Transmit() call, faster than
     * the inherited byte by byte version. Blocks until they have been sent.
     * HAL_UART_Transmit() takes a uint16_t size, so larger blocks are sent in parts.
     * @param buf the bytes to send
     * @param size the number of bytes
     * @return the number of bytes sent, 0 if begin() has not been called
     */
    size_t write(const uint8_t *buf, size_t size) override;

    /**
     * Wait until all bytes previously written have been sent.
     * write() blocks until each byte has gone out, so there is nothing to wait for.
     */
    void flush() override;

    // pfodStream methods

    /**
     * Number of received bytes waiting in the rx ring buffer.
     * @return the number of bytes available, 0 if none (or begin() not called).
     */
    int available() override;

    /**
     * Read and remove the next received byte from the rx ring buffer.
     * Does not block.
     * @return the next byte (0..255) as an int, or -1 if no byte is available.
     */
    int read() override;

    /**
     * Return the next received byte WITHOUT removing it.
     * Does not block.
     * @return the next byte (0..255) as an int, or -1 if no byte is available.
     */
    int peek() override;

    /**
     * @return the HAL UART handle passed to begin(), NULL before begin()
     */
    UART_HandleTypeDef* getHandle() const { return huart; }

    /**
     * Called from HAL_UART_RxCpltCallback() (interrupt context) when the
     * requested byte has arrived. Stores it in the rx ring buffer (dropped if
     * full) and requests the next byte. Not for direct use.
     */
    void onByteReceived();

  private:
    UART_HandleTypeDef *huart; // set by begin(), NULL until then, no i/o until then
    pfodRingBuffer rxRingBuffer;
    uint8_t rxByte; // single byte landing zone for HAL_UART_Receive_IT()
};

#endif //target_Stream_h
