# build.sh -- builds this OnOff_Serial example for an STM32F401RE (e.g. Nucleo-F401RE)
# with the STM32CubeF4 HAL and arm-none-eabi-gcc, without STM32CubeIDE.
#
# This checks that the example compiles and links against the real HAL. main.cpp
# still has its TODO: HAL_Init(), SystemClock_Config(), the USART2 / GPIO setup and
# USART2_IRQHandler() (normally generated by CubeMX) must be added before it does
# anything on a board.
#
# Run from Git Bash (Windows), or bash on Linux / macOS:
#   bash build.sh               build
#   bash build.sh --delete-sdk  build, then delete the HAL files build.sh downloaded
# Output, in build/ in this directory: OnOff_Serial.elf / .map / .bin / .hex
#
# The HAL comes from (first found):
#   1. STM32CUBE_F4, the path of an STM32CubeF4 firmware package, e.g. one STM32CubeIDE /
#      CubeMX installed in ~/STM32Cube/Repository/STM32Cube_FW_F4_V1.28.x
#   2. the highest STM32Cube_FW_F4_* in ~/STM32Cube/Repository
#   3. otherwise a shallow git clone (about 40MB) into build/stm32sdk of
#      github.com/STMicroelectronics/stm32f4xx-hal-driver and cmsis-device-f4, plus the
#      CMSIS core headers from github.com/ARM-software/CMSIS_5 (needs git and curl).
#      It is kept for the next build unless --delete-sdk is given.
# The toolchain comes from (first found):
#   1. STM32_GCC_BIN, the bin directory of an arm-none-eabi-gcc toolchain
#   2. arm-none-eabi-gcc on the PATH
#   3. the highest packages/*/tools/arm-none-eabi-gcc/*/bin in Arduino15 (e.g. installed
#      with an Arduino SAMD / Adafruit / Seeeduino core); ARDUINO15 overrides its location
# PFOD_PARSER_CPP overrides the pfodParserCPP directory, default three directories up from here.
#
# For another STM32F4: change MCU_DEFINE and STARTUP below and the FLASH / RAM sizes in
# STM32F401RE.ld. For another family, also the HAL / device repos, the -mcpu/-mfpu
# flags and PFOD_STM32_HAL_INCLUDE (see target_Stream.h).

set -u

MCU_DEFINE=STM32F401xE            # the CMSIS device define for the part
STARTUP=startup_stm32f401xe.s     # the CMSIS device gcc startup file for the part
LDSCRIPT=STM32F401RE.ld           # in this directory
MCU="-mcpu=cortex-m4 -mthumb -mfpu=fpv4-sp-d16 -mfloat-abi=hard"

EX="$(cd "$(dirname "$0")" && pwd)"
ROOT="${PFOD_PARSER_CPP:-$EX/../../..}"
OUT="$EX/build"
DELETE_SDK=0
[ "${1:-}" = "--delete-sdk" ] && DELETE_SDK=1

# toPath -- convert a path for the native tools (C:/... form under Git Bash on Windows)
toPath() {
  if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else echo "$1"; fi
}

# fail -- print an error and stop
fail() {
  echo "ERROR: $*" >&2
  exit 1
}

# ---- toolchain ----
if [ -n "${STM32_GCC_BIN:-}" ]; then
  TC="$STM32_GCC_BIN/arm-none-eabi-"
elif command -v arm-none-eabi-gcc >/dev/null 2>&1; then
  TC="arm-none-eabi-"
else
  if [ -z "${ARDUINO15:-}" ]; then
    if [ -n "${LOCALAPPDATA:-}" ]; then ARDUINO15="$(toPath "$LOCALAPPDATA")/Arduino15"
    elif [ "$(uname)" = "Darwin" ]; then ARDUINO15="$HOME/Library/Arduino15"
    else ARDUINO15="$HOME/.arduino15"; fi
  fi
  TCDIR="$(ls -d "$ARDUINO15"/packages/*/tools/arm-none-eabi-gcc/*/bin 2>/dev/null | sort -V | tail -1)"
  [ -n "$TCDIR" ] || fail "no arm-none-eabi-gcc found, set STM32_GCC_BIN"
  TC="$TCDIR/arm-none-eabi-"
fi
"${TC}gcc" --version >/dev/null 2>&1 || fail "cannot run ${TC}gcc"
echo "Toolchain: $("${TC}gcc" --version | head -1)"

# ---- HAL ----
SDK_DOWNLOAD="$OUT/stm32sdk"
if [ -z "${STM32CUBE_F4:-}" ]; then
  STM32CUBE_F4="$(ls -d "$HOME"/STM32Cube/Repository/STM32Cube_FW_F4_* 2>/dev/null | sort -V | tail -1)"
fi
if [ -n "$STM32CUBE_F4" ]; then
  [ -d "$STM32CUBE_F4/Drivers/STM32F4xx_HAL_Driver" ] || fail "$STM32CUBE_F4 is not an STM32CubeF4 package"
  HAL="$STM32CUBE_F4/Drivers/STM32F4xx_HAL_Driver"
  DEVICE="$STM32CUBE_F4/Drivers/CMSIS/Device/ST/STM32F4xx"
  CMSIS="$STM32CUBE_F4/Drivers/CMSIS/Include"
  DELETE_SDK=0 # never delete a package build.sh did not download
  echo "HAL: $STM32CUBE_F4"
else
  HAL="$SDK_DOWNLOAD/hal"
  DEVICE="$SDK_DOWNLOAD/device"
  CMSIS="$SDK_DOWNLOAD/cmsis"
  if [ ! -d "$HAL/Src" ]; then
    echo "Downloading the STM32F4 HAL into $SDK_DOWNLOAD"
    mkdir -p "$SDK_DOWNLOAD"
    git clone -q --depth 1 https://github.com/STMicroelectronics/stm32f4xx-hal-driver.git "$HAL" || fail "git clone of the HAL failed"
    git clone -q --depth 1 https://github.com/STMicroelectronics/cmsis-device-f4.git "$DEVICE" || fail "git clone of cmsis-device-f4 failed"
    mkdir -p "$CMSIS"
    for f in core_cm4.h cmsis_compiler.h cmsis_gcc.h cmsis_version.h mpu_armv7.h; do
      curl -sfL -o "$CMSIS/$f" "https://raw.githubusercontent.com/ARM-software/CMSIS_5/develop/CMSIS/Core/Include/$f" || fail "download of $f failed"
    done
  fi
  echo "HAL: $SDK_DOWNLOAD (downloaded)"
fi

# ---- build ----
rm -rf "$OUT/obj" "$OUT/hal" "$OUT/conf" "$OUT"/OnOff_Serial.*
mkdir -p "$OUT/obj" "$OUT/hal" "$OUT/conf"
: > "$OUT/warnings.txt"
# the HAL's default configuration (all modules enabled, HSE 25MHz); a CubeMX project generates its own
if [ -e "$HAL/Inc/stm32f4xx_hal_conf_template.h" ]; then
  cp "$HAL/Inc/stm32f4xx_hal_conf_template.h" "$OUT/conf/stm32f4xx_hal_conf.h"
else
  cp "$DEVICE/Source/Templates/gcc/stm32f4xx_hal_conf_template.h" "$OUT/conf/stm32f4xx_hal_conf.h" 2>/dev/null \
    || fail "stm32f4xx_hal_conf_template.h not found"
fi

P() { toPath "$1"; }
INC="-I$(P "$EX") -I$(P "$ROOT/src") -I$(P "$OUT/conf") -I$(P "$HAL/Inc") -I$(P "$DEVICE/Include") -I$(P "$CMSIS")"
COMMON="$MCU -D$MCU_DEFINE -DUSE_HAL_DRIVER $INC -Os -g -ffunction-sections -fdata-sections"

errors=0
# the HAL modules used, plus the device system file -- ST's code, its warnings are not shown
for f in "$HAL"/Src/stm32f4xx_hal.c "$HAL"/Src/stm32f4xx_hal_{cortex,gpio,rcc,rcc_ex,uart,dma,dma_ex,pwr,pwr_ex}.c \
         "$DEVICE/Source/Templates/system_stm32f4xx.c"; do
  "${TC}gcc" -c -std=gnu11 $COMMON -w "$(P "$f")" -o "$(P "$OUT/hal/$(basename "${f%.*}").o")" || { echo "compile failed: $f"; errors=1; }
done
"${TC}gcc" -c $MCU -x assembler-with-cpp "$(P "$DEVICE/Source/Templates/gcc/$STARTUP")" -o "$(P "$OUT/hal/startup.o")" || { echo "assemble failed: $STARTUP"; errors=1; }
# this example and pfodParserCPP, with warnings
for f in "$EX"/*.cpp "$ROOT"/src/*.cpp "$ROOT"/src/dwgs/*.cpp; do
  "${TC}g++" -c -std=gnu++11 $COMMON -Wall -Wextra -fno-exceptions -fno-rtti -fno-threadsafe-statics \
    "$(P "$f")" -o "$(P "$OUT/obj/$(basename "${f%.*}").o")" 2>>"$OUT/warnings.txt" || { echo "compile failed: $f"; errors=1; }
done
for f in "$ROOT"/src/*.c; do
  "${TC}gcc" -c -std=gnu11 $COMMON -Wall -Wextra "$(P "$f")" -o "$(P "$OUT/obj/$(basename "${f%.*}").o")" 2>>"$OUT/warnings.txt" || { echo "compile failed: $f"; errors=1; }
done
[ -s "$OUT/warnings.txt" ] && cat "$OUT/warnings.txt"
[ $errors = 0 ] || fail "compile failed"

"${TC}g++" $MCU "-T$(P "$EX/$LDSCRIPT")" -specs=nano.specs -specs=nosys.specs -Wl,--gc-sections \
  "-Wl,-Map=$(P "$OUT/OnOff_Serial.map")" "$(P "$OUT")"/hal/*.o "$(P "$OUT")"/obj/*.o \
  -o "$(P "$OUT/OnOff_Serial.elf")" || fail "link failed"
"${TC}size" "$(P "$OUT/OnOff_Serial.elf")"
"${TC}objcopy" -O binary "$(P "$OUT/OnOff_Serial.elf")" "$(P "$OUT/OnOff_Serial.bin")"
"${TC}objcopy" -O ihex "$(P "$OUT/OnOff_Serial.elf")" "$(P "$OUT/OnOff_Serial.hex")"
echo "Built $OUT/OnOff_Serial.elf / .bin / .hex"

if [ $DELETE_SDK = 1 ]; then
  rm -rf "$SDK_DOWNLOAD"
  echo "Deleted the downloaded HAL $SDK_DOWNLOAD"
fi
